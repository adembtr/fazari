"""Build site/data/exoplanet_hosts.json: stars with known planets, from the NASA Exoplanet Archive.

One TAP query to the Planetary Systems Composite Parameters table (pscomppars, doi:10.26133/NEA13),
one row per planet, reduced here to one row per host star. The explorer (site/explore/planets.js) and the
result viewer use it to say "this star has N known planets" and to link the archive's overview page.

Positions: pscomppars has no epoch column. Checked on 2026-11-14 against our Gaia DR3 fast-star list
(site/data/fast_stars.json.gz): hosts with a Gaia DR2 id sit at their Gaia DR2 position, epoch 2015.5
(54 of 55 hosts faster than 1"/yr, residual < 0.01"); hosts without one sit near J2000 (GJ 273 1999.98,
GJ 411 1998.2, Gl 725 B 2000.3). So epoch = 2015.5 with a DR2 id, else 2000.0 (approximate: match those
with a wider radius).

Usage:
  uv run --no-project python -I pipeline/exoplanet_hosts.py [--csv saved_query.csv] [--out site/data/exoplanet_hosts.json]
Without --csv the query is sent to the archive. An existing output file is never overwritten (use a new
--out name). The downloaded table is treated as untrusted: every field is type- and range-checked.
"""
import argparse
import csv
import io
import json
import math
import re
import sys
import urllib.parse
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TAP = "https://exoplanetarchive.ipac.caltech.edu/TAP/sync"
QUERY = ("select hostname,ra,dec,sy_pmra,sy_pmdec,sy_plx,sy_dist,sy_pnum,sy_snum,gaia_dr2_id,gaia_dr3_id,"
         "hd_name,hip_name,sy_gaiamag,sy_kmag from pscomppars")
OVERVIEW = "https://exoplanetarchive.ipac.caltech.edu/overview/{host}"
ACK = ("This research has made use of the NASA Exoplanet Archive, which is operated by the California Institute "
       "of Technology, under contract with the National Aeronautics and Space Administration under the Exoplanet "
       "Exploration Program.")
AI_DISCLOSURE = ("Made by Fazari pipeline code written with help from Anthropic's Claude (Claude Code) and checked "
                 "by Team Fazari; every value is copied from the NASA Exoplanet Archive table named in 'query', "
                 "not generated by an AI model.")
NAME_OK = re.compile(r"^[\w .'+\-()/*,:&]{1,60}$")


def num(v, lo, hi, nd=None):
    """Float in [lo, hi] or None for an empty cell; anything else is an error."""
    if v is None or str(v).strip() == "":
        return None
    x = float(v)
    if not math.isfinite(x) or not lo <= x <= hi:
        raise ValueError(f"out of range: {v}")
    return round(x, nd) if nd is not None else x


def gaia(v, release):
    v = (v or "").strip()
    if not v:
        return None
    m = re.fullmatch(rf"Gaia {release} (\d{{6,20}})", v)
    if not m:
        raise ValueError(f"bad Gaia id: {v}")
    return m.group(1)


def fetch():
    url = TAP + "?" + urllib.parse.urlencode({"query": QUERY, "format": "csv"})
    with urllib.request.urlopen(url, timeout=120) as r:
        return r.read().decode("utf-8")


def build(text, fetched):
    hosts, bad, planets, conflicts = {}, 0, 0, 0
    for r in csv.DictReader(io.StringIO(text)):
        planets += 1
        try:
            name = (r["hostname"] or "").strip()
            if not NAME_OK.match(name):
                raise ValueError(f"bad host name: {name!r}")
            dr2 = gaia(r["gaia_dr2_id"], "DR2")
            row = {
                "host": name,
                "ra": num(r["ra"], 0, 360, 7) % 360.0,
                "dec": num(r["dec"], -90, 90, 7),
                "pmra": num(r["sy_pmra"], -2e4, 2e4, 3),
                "pmdec": num(r["sy_pmdec"], -2e4, 2e4, 3),
                "epoch": 2015.5 if dr2 else 2000.0,
                "n": int(r["sy_pnum"]),
                "plx": num(r["sy_plx"], -50, 2000, 3),
                "dist_pc": num(r["sy_dist"], 0, 1e6, 3),
                "gaia_dr3": gaia(r["gaia_dr3_id"], "DR3"),
            }
            if row["ra"] is None or row["dec"] is None or not 1 <= row["n"] <= 50:
                raise ValueError("missing position or planet count")
        except (ValueError, KeyError, TypeError) as e:
            bad += 1
            print("skipped:", e, file=sys.stderr)
            continue
        old = hosts.get(name)
        if old is None:
            hosts[name] = row
        elif old != row:
            conflicts += 1                       # system values should be the same on every planet row
            old["n"] = max(old["n"], row["n"])
    fields = ["host", "ra", "dec", "pmra", "pmdec", "epoch", "n", "plx", "dist_pc", "gaia_dr3"]
    rows = [[h[f] for f in fields] for h in sorted(hosts.values(), key=lambda h: (h["ra"], h["dec"]))]
    doc = {
        "_note": ("Stars with known planets (confirmed planets in the NASA Exoplanet Archive), one row per host. "
                  "ra/dec in degrees (ICRS) at 'epoch'; pmra = mu_alpha*cos(dec) and pmdec in mas/yr; n = number of "
                  "known planets in the system; plx (mas) and dist_pc from the archive (they disagree for a few hosts without "
                  "Gaia ids, e.g. GJ 273 and GJ 411: use plx for nearby stars). epoch: 2015.5 for hosts with a Gaia DR2 id "
                  "(their archive position is the Gaia DR2 one), else about 2000.0. Move a position with its proper "
                  "motion before matching it to an observation. Built by pipeline/exoplanet_hosts.py."),
        "source": "NASA Exoplanet Archive, Planetary Systems Composite Parameters table (pscomppars)",
        "doi": "10.26133/NEA13",
        "tap": TAP,
        "query": QUERY,
        "retrieved": fetched,
        "planet_rows": planets,
        "host_rows": len(rows),
        "skipped_rows": bad,
        "conflicting_rows": conflicts,
        "overview_url": OVERVIEW,
        "overview_note": "Replace {host} with the URL-encoded host name (encodeURIComponent).",
        "acknowledgement": ACK,
        "ai_disclosure": AI_DISCLOSURE,
        "fields": fields,
        "hosts": rows,
    }
    return doc


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--csv", help="a saved CSV answer of QUERY (else the archive is queried)")
    ap.add_argument("--retrieved", help="UTC time the CSV was retrieved (with --csv)")
    ap.add_argument("--out", default=str(ROOT / "site" / "data" / "exoplanet_hosts.json"))
    a = ap.parse_args()
    out = Path(a.out)
    if out.exists():
        sys.exit(f"{out} exists; not overwritten (choose another --out)")
    if a.csv:
        text, fetched = Path(a.csv).read_text(encoding="utf-8"), a.retrieved or "unknown"
    else:
        text, fetched = fetch(), datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    doc = build(text, fetched)
    rows = doc.pop("hosts")                      # header readable, then one host per line
    head = json.dumps(doc, indent=1, ensure_ascii=False)
    body = ",\n".join(json.dumps(r, separators=(",", ":"), ensure_ascii=False) for r in rows)
    out.write_text(head[:-2] + ',\n "hosts": [\n' + body + "\n ]\n}\n")
    doc["hosts"] = rows
    print(f"{out}: {doc['host_rows']} hosts from {doc['planet_rows']} planet rows "
          f"({doc['skipped_rows']} skipped, {doc['conflicting_rows']} conflicting), {out.stat().st_size} bytes")


if __name__ == "__main__":
    main()
